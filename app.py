import streamlit as st
import folium
from streamlit_folium import st_folium
from databricks.sdk import WorkspaceClient

st.set_page_config(
    page_title="NYC Taxi Fare Prediction",
    page_icon="🚕",
    layout="centered"
)

st.title("🚕 NYC Taxi Fare Prediction")
st.write("Predict your taxi fare using a Machine Learning model.")

st.divider()

# ---------------------------------------------------------
# NYC MAP
# ---------------------------------------------------------

st.subheader("🗺️ Select Your Trip Locations")

st.write(
    "Click on the map to select your pickup and drop-off locations."
)

# Default NYC coordinates
nyc_lat = 40.7580
nyc_lon = -73.9855

m = folium.Map(
    location=[nyc_lat, nyc_lon],
    zoom_start=11
)

# Add a marker for the pickup location
folium.Marker(
    [40.7580, -73.9855],
    popup="Pickup Location",
    tooltip="Pickup",
    icon=folium.Icon(icon="play")
).add_to(m)

# Add a marker for the drop-off location
folium.Marker(
    [40.7306, -73.9352],
    popup="Drop-off Location",
    tooltip="Drop-off",
    icon=folium.Icon(icon="flag")
).add_to(m)

map_data = st_folium(
    m,
    width=700,
    height=450
)

st.divider()

# ---------------------------------------------------------
# TRIP DETAILS
# ---------------------------------------------------------

st.subheader("Enter Trip Details")

col1, col2 = st.columns(2)

with col1:

    trip_distance = st.number_input(
        "Trip Distance (miles)",
        min_value=0.1,
        value=2.5,
        step=0.1
    )

    passenger_count = st.number_input(
        "Passenger Count",
        min_value=1,
        max_value=6,
        value=2,
        step=1
    )

    trip_duration = st.number_input(
        "Trip Duration (minutes)",
        min_value=1.0,
        value=20.0,
        step=1.0
    )

    pickup_hour = st.number_input(
        "Pickup Hour (0–23)",
        min_value=0,
        max_value=23,
        value=18,
        step=1
    )


with col2:

    pickup_month = st.number_input(
        "Pickup Month (1–4)",
        min_value=1,
        max_value=4,
        value=3,
        step=1
    )

    pickup_day_of_week = st.number_input(
        "Pickup Day of Week (0–6)",
        min_value=0,
        max_value=6,
        value=2,
        step=1
    )

    pu_location = st.number_input(
        "Pickup Location ID",
        min_value=1,
        value=161,
        step=1
    )

    do_location = st.number_input(
        "Drop-off Location ID",
        min_value=1,
        value=236,
        step=1
    )

st.divider()

# ---------------------------------------------------------
# PREDICTION
# ---------------------------------------------------------

if st.button("🔮 Predict Fare", use_container_width=True):

    try:

        with st.spinner("Predicting your taxi fare..."):

            workspace = WorkspaceClient(
                host=st.secrets["DATABRICKS_HOST"],
                client_id=st.secrets["DATABRICKS_CLIENT_ID"],
                client_secret=st.secrets["DATABRICKS_CLIENT_SECRET"]
            )

            response = workspace.serving_endpoints.query(
                name="taxi-fare-prediction-endpoint",
                dataframe_records=[
                    {
                        "trip_distance": trip_distance,
                        "passenger_count": passenger_count,
                        "pickup_hour": pickup_hour,
                        "pickup_month": pickup_month,
                        "pickup_day_of_week": pickup_day_of_week,
                        "trip_duration_minutes": trip_duration,
                        "PULocationID": pu_location,
                        "DOLocationID": do_location
                    }
                ]
            )

            prediction = response.predictions[0]

        st.success(
            f"💰 Predicted Taxi Fare: ${prediction:.2f}"
        )

        st.caption(
            "Prediction generated by a deployed Random Forest model."
        )

    except Exception as e:

        st.error(
            f"Prediction failed: {type(e).__name__}: {e}"
        )
